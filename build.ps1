# Builds index.html (single file, CSS and JS inline) at the repo root and the
# WordPress theme from the sources in src/. Run:
#
#   powershell -ExecutionPolicy Bypass -File build.ps1
#
# Edit src/_head.html, src/_body.html, src/css/theme.css or src/js/main.js.
# Never edit index.html or the theme's style.css, front-page.php or main.js:
# they are generated and will be overwritten.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$src = Join-Path $root 'src'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Src($name) { [IO.File]::ReadAllText((Join-Path $src $name), $utf8) }
function Write-Out($path, $text) {
  $dir = Split-Path $path
  if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
  [IO.File]::WriteAllText($path, $text.Replace("`r`n", "`n"), $utf8)
}

$head = Read-Src '_head.html'
$body = Read-Src '_body.html'
$css  = (Read-Src 'css\theme.css').Replace('{{A}}', 'assets/')
$js   = Read-Src 'js\main.js'

# ---------------- static HTML ----------------
$htmlBody = $body.Replace('{{A}}', 'assets/')
$htmlBody = [regex]::Replace($htmlBody, '<!--WP:[a-z-]+-->', '')
$html = "<!doctype html>`n<html lang=""en"">`n<head>`n$head<style>`n$css</style>`n</head>`n<body>`n$htmlBody`n<script>`n$js</script>`n</body>`n</html>`n"
Write-Out (Join-Path $root 'index.html') $html
"index.html  $([math]::Round($html.Length / 1KB)) KB"

# ---------------- WordPress theme ----------------
$theme = Join-Path $root 'wordpress-theme'

$styleHeader = @'
/*
Theme Name: Selective Solutions
Theme URI: https://selectivesolutions.com/
Author: Zaphyre
Description: One-page landing theme for Selective Solutions LLC: managed IT, VoIP phone systems, cybersecurity and backup for Georgia businesses. Set a static front page under Settings > Reading.
Version: 1.0.0
Requires at least: 6.0
Requires PHP: 7.4
License: GNU General Public License v2 or later
License URI: https://www.gnu.org/licenses/gpl-2.0.html
Text Domain: selsol
*/

/* WordPress admin bar offset for the fixed header. */
body.admin-bar .site-head { top: 32px; }
@media screen and (max-width: 782px) { body.admin-bar .site-head { top: 46px; } }
@media screen and (max-width: 600px) { body.admin-bar .site-head { top: 0; } }

'@
Write-Out (Join-Path $theme 'style.css') ($styleHeader + $css)
Write-Out (Join-Path $theme 'assets\js\main.js') $js

$wp = $body.Replace('{{A}}', '<?php echo esc_url( $selsol_a ); ?>')
$wp = $wp.Replace('action="mailto:info@selectivesolutions.com"', 'action="<?php echo esc_url( admin_url( ''admin-post.php'' ) ); ?>"')
$wp = $wp.Replace('data-mode="mailto"', 'data-mode="wp"')
$wp = $wp.Replace('<!--WP:contact-fields-->', '<input type="hidden" name="action" value="selsol_contact"><?php wp_nonce_field( ''selsol_contact'', ''selsol_nonce'' ); ?>')
$wp = $wp.Replace('<!--WP:callback-fields-->', '<input type="hidden" name="action" value="selsol_callback"><?php wp_nonce_field( ''selsol_callback'', ''selsol_nonce'' ); ?>')
$wp = $wp.Replace('<!--WP:contact-status-->', '<?php echo esc_html( $selsol_contact[1] ); ?>')
$wp = $wp.Replace('<!--WP:callback-status-->', '<?php echo esc_html( $selsol_callback[1] ); ?>')
$wp = $wp.Replace('class="form__status" id="form-status"', 'class="form__status <?php echo esc_attr( $selsol_contact[0] ); ?>" id="form-status"')
if ($wp -match '<!--WP:') { throw 'Unreplaced WP marker in body' }

$frontPage = @'
<?php
/**
 * Front page. Generated by build.ps1 from src/_body.html: edit the source, not this file.
 *
 * @package SelectiveSolutions
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$selsol_a        = get_theme_file_uri( 'assets/' );
$selsol_contact  = selsol_form_status( 'contact' );
$selsol_callback = selsol_form_status( 'callback' );
?><!doctype html>
<html <?php language_attributes(); ?>>
<head>
<meta charset="<?php bloginfo( 'charset' ); ?>">
<meta name="viewport" content="width=device-width, initial-scale=1">
<?php wp_head(); ?>
</head>
<body <?php body_class(); ?>>
<?php wp_body_open(); ?>

'@ + $wp + @'

<?php wp_footer(); ?>
</body>
</html>

'@
Write-Out (Join-Path $theme 'front-page.php') $frontPage

foreach ($sub in 'images', 'video') {
  $dst = Join-Path $theme "assets\$sub"
  # Mirror the folder so files removed from assets/ also leave the theme.
  if (Test-Path $dst) { Remove-Item (Join-Path $dst '*') -Force }
  New-Item -ItemType Directory -Force $dst | Out-Null
  Copy-Item (Join-Path $root "assets\$sub\*") $dst -Force
}
"wordpress-theme regenerated"
